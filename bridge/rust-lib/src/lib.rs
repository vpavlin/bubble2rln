#[derive(Default)]
struct AllocationClient;

/// "Sent, but not on chain within the gifter's window" is not a failure on a slow chain:
/// liblogos_rln_module marks a record failed on any `error` reply, and a failed record it can
/// never drop. Answer it as accepted (no leaf yet), so the record stays pending and the
/// module's poller reads the registration back when it lands.
fn pending_if_unconfirmed(v: serde_json::Value) -> serde_json::Value {
    if v.get("kind").and_then(|k| k.as_str()) != Some("unconfirmed") {
        return v;
    }
    let err = v.get("error").and_then(|e| e.as_str()).unwrap_or("");
    let tx = err.split("(tx ").nth(1).and_then(|t| t.split(')').next()).unwrap_or("");
    serde_json::json!({ "pending": true, "tx_hash": tx, "note": err })
}

/// liblogos_rln_module (0.12.x) calls `rln_gifter_module.request` with the RLN-gifter names
/// (gifterPeerId / gifterMultiaddr) and no registry; the allocation client wants
/// allocatorPeerId / allocatorMultiaddr / discover, and `config` when it should be named.
/// Map the one onto the other; a `config` inside authArgs (a JSON object) names the registry.
fn bridge_args(args_json: &str) -> String {
    let Ok(mut a) = serde_json::from_str::<serde_json::Value>(args_json) else {
        return args_json.to_string();
    };
    let Some(o) = a.as_object_mut() else { return args_json.to_string() };
    if let Some(p) = o.remove("gifterPeerId") {
        if !p.as_str().unwrap_or("").is_empty() { o.entry("allocatorPeerId").or_insert(p); }
    }
    if let Some(m) = o.remove("gifterMultiaddr") {
        if !m.as_str().unwrap_or("").is_empty() { o.entry("allocatorMultiaddr").or_insert(m); }
    }
    if o.contains_key("allocatorPeerId") && o.contains_key("allocatorMultiaddr") && !o.contains_key("discover") {
        o.insert("discover".into(), serde_json::Value::Bool(false));
    }
    if !o.contains_key("config") {
        let cfg = o.get("authArgs").and_then(|v| v.as_str())
            .and_then(|s| serde_json::from_str::<serde_json::Value>(s).ok())
            .and_then(|v| v.get("config").and_then(|c| c.as_str()).map(str::to_owned));
        if let Some(c) = cfg { o.insert("config".into(), c.into()); }
    }
    a.to_string()
}

fn reply(r: Result<serde_json::Value, serde_json::Value>) -> String {
    match r {
        Ok(v) | Err(v) => v.to_string(),
    }
}

impl RlnGifterModule for AllocationClient {
    fn request(&mut self, args_json: String) -> String {
        reply(client::request(&bridge_args(&args_json)).map_err(pending_if_unconfirmed))
    }

    fn discover(&mut self, args_json: String) -> String {
        reply(client::discover(&args_json))
    }

    fn on_context_ready(&mut self, _ctx: &RustModuleContext) {
        lp::init(&[lp::LIBP2P_MODULE]);
    }
}

#[no_mangle]
pub extern "Rust" fn logos_module_install() {
    install::<AllocationClient>();
}
